import { describe, expect, it } from "vitest";

import {
  generateSingleSourceReference,
  stripAutoGeneratedReferences,
} from "@/features/create-pages/create-shared/utils/auto-reference";

describe("generateSingleSourceReference", () => {
  it("writes Based on PQ / PO lines with the document number", () => {
    expect(generateSingleSourceReference("PurchaseQuotation", "132424", "C1105")).toBe(
      "Based on PQ 132424",
    );
    expect(generateSingleSourceReference("PurchaseOrder", "5001", "")).toBe("Based on PO 5001");
    expect(generateSingleSourceReference("PurchaseOrder", "5001")).toBe("Based on PO 5001");
  });

  it("stripAutoGeneratedReferences removes Based on and legacy lines", () => {
    const remarks = [
      "Urgent for plant B",
      "Based on PQ 132424",
      "PQ 132424",
      "Auto Generated Based on C1105 Purchase Quotation 132424",
      "Based on Purchase Order 188",
    ].join("\n");
    expect(stripAutoGeneratedReferences(remarks)).toBe("Urgent for plant B");
  });
});
