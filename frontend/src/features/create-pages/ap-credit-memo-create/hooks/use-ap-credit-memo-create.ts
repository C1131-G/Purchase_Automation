      const userRemarks = commentLines
        .filter((line) => !/^based on /i.test(line))
        .join("\n")
        .trim();
      const remarksParts = [refLinesFromComments.join("\n"), autoReference, userRemarks]
        .filter(Boolean)
        .join("\n")
