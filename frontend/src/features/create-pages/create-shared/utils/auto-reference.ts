/**
 * Auto-reference utilities for document copy operations.
 * Short "Based on {TYPE} {num}" lines for SAP Comments (254 max).
 */

/** @deprecated Old long-form prefix; new lines use Based on PQ 123. */
export const AUTO_GENERATED_PREFIX = "Auto Generated";

/** Short type codes written into remarks. */
const DOC_TYPE_SHORT: Record<string, string> = {
  APCreditMemo: "CM",
  APInvoice: "AP",
  GoodsReceiptPO: "GRPO",
  OutgoingPayment: "OP",
  PurchaseOrder: "PO",
  PurchaseQuotation: "PQ",
};

const DOC_TYPE_SHORT_PLURAL: Record<string, string> = {
  APCreditMemo: "CM",
  APInvoice: "AP",
  GoodsReceiptPO: "GRPO",
  OutgoingPayment: "OP",
  PurchaseOrder: "PO",
  PurchaseQuotation: "PQ",
};

const SHORT_CODES = "PQD|PQ|RFQ|SQ|PO|AR|GRPO|AP|CM|OP";

/** Short auto-ref: `Based on PQ 132424`, legacy `PQ 132424`, … */
const SHORT_AUTO_REF_LINE_RE = new RegExp(`^(${SHORT_CODES})\\s*:?\\s+\\S+`, "i");

const LONG_LABEL_TO_KEY: Array<{ label: string; key: string }> = [
  { key: "PQ", label: "purchase quotation drafts" },
  { key: "PQ", label: "purchase quotation draft" },
  { key: "RFQ", label: "request for quotations" },
  { key: "RFQ", label: "request for quotation" },
  { key: "PQ", label: "purchase quotations" },
  { key: "PQ", label: "purchase quotation" },
  { key: "SQ", label: "sales quotations" },
  { key: "SQ", label: "sales quotation" },
  { key: "PO", label: "purchase orders" },
  { key: "PO", label: "purchase order" },
];

export const normalizeRemarkNewlines = (value: string): string =>
  value.replace(/\r\n/g, "\n").replace(/\r/g, "\n");

export const splitRemarkLines = (value: string): string[] =>
  normalizeRemarkNewlines(value)
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

const normalizeRemarkKey = (key: string): string => {
  const upper = key.trim().toUpperCase();
  return upper === "PQD" ? "PQ" : upper;
};

/** Parse one auto line to key + doc number (short, long, SAP plural). */
export const parseAutoRemarkKeyAndNum = (line: string): { key: string; num: string } | null => {
  const trimmed = line.trim().replace(/^auto\s+generated\s+/i, "");
  if (!trimmed) {
    return null;
  }
  const short = trimmed.match(
    new RegExp(`^(?:based on\\s+)?(${SHORT_CODES})\\s*:?\\s+(\\S+)`, "i"),
  );
  if (short?.[1] && short[2]) {
    return { key: normalizeRemarkKey(short[1]), num: short[2].trim() };
  }
  const rest = trimmed.replace(/^based on\s+/i, "").trim();
  for (const { label, key } of LONG_LABEL_TO_KEY) {
    const pattern = new RegExp(`^(?:.+?\\s+)?${label}\\s+(\\S+)\\s*$`, "i");
    const match = rest.match(pattern);
    if (match?.[1]) {
      return { key: normalizeRemarkKey(key), num: match[1].trim() };
    }
  }
  return null;
};

/**
 * True for system reference lines (new Based on TYPE + legacy forms).
 */
export const isAutoGeneratedRemarkLine = (line: string): boolean => {
  const trimmed = line.trim();
  if (!trimmed) {
    return false;
  }
  if (/^(?:auto\s+generated\s+)?based on\s+/i.test(trimmed)) {
    return true;
  }
  if (/^IC\s*\|/i.test(trimmed)) {
    return true;
  }
  return SHORT_AUTO_REF_LINE_RE.test(trimmed);
};

const shortCodeFor = (docType: string): string => DOC_TYPE_SHORT[docType] || docType;

/**
 * Single source: `Based on PQ 132424` (no company name).
 */
export function generateSingleSourceReference(
  docType: string,
  docNum: string,
  _companyCode?: string | null,
): string {
  const code = shortCodeFor(docType);
  const num = String(docNum).trim();
  return num ? `Based on ${code} ${num}` : `Based on ${code}`;
}

/**
 * Multiple sources, same type: `Based on PO 1, 2, 3` or `Based on 3 PO` when mixed nums not listed.
 * Mixed types: `Based on 3 docs`.
 */
export function generateMultiSourceReference(
  documents: { docType: string; docNum: string; companyCode?: string | null }[],
): string {
  const count = documents.length;
  if (count === 0) {
    return "";
  }
  if (count === 1) {
    return generateSingleSourceReference(
      documents[0]!.docType,
      documents[0]!.docNum,
      documents[0]!.companyCode,
    );
  }

  const firstType = documents[0]!.docType;
  const allSameType = documents.every((doc) => doc.docType === firstType);

  if (allSameType) {
    const code = DOC_TYPE_SHORT_PLURAL[firstType] || shortCodeFor(firstType);
    if (count <= 5) {
      const nums = documents.map((doc) => String(doc.docNum).trim()).filter(Boolean);
      if (nums.length === count) {
        return `Based on ${code} ${nums.join(", ")}`;
      }
    }
    return `Based on ${count} ${code}`;
  }

  return `Based on ${count} docs`;
}

/**
 * Short list summary for many sources.
 */
export function generateShortDocListSummary(
  documents: { docType: string; docNum: string; companyCode?: string | null }[],
): string {
  const count = documents.length;
  if (count === 0) {
    return "";
  }
  if (count === 1) {
    return generateSingleSourceReference(
      documents[0]!.docType,
      documents[0]!.docNum,
      documents[0]!.companyCode,
    );
  }

  const firstType = documents[0]!.docType;
  const allSameType = documents.every((doc) => doc.docType === firstType);
  const code = allSameType ? shortCodeFor(firstType) : "doc";

  if (count <= 3) {
    const docNums = documents.map((doc) => String(doc.docNum).trim()).join(", ");
    return `Based on ${code} ${docNums}`;
  }

  const shownNums = documents
    .slice(0, 3)
    .map((doc) => String(doc.docNum).trim())
    .join(", ");
  const remaining = count - 3;
  return `Based on ${code} ${shownNums} (+${remaining})`;
}

/**
 * Extracts source document metadata from a reference string.
 * Returns null if the reference doesn't match expected format.
 */
export function parseReferenceToSourceDocs(
  reference: string,
): { docType: string; docNum: string }[] | null {
  if (!isAutoGeneratedRemarkLine(reference)) {
    return null;
  }
  return null;
}

/**
 * Strips auto-generated reference lines from remarks while preserving user text.
 * Matches `Based on PQ 123`, short `PQ 123`, and legacy long forms.
 */
export function stripAutoGeneratedReferences(remarks: string): string {
  if (!remarks) {
    return "";
  }

  const lines = splitRemarkLines(remarks);
  const userLines = lines.filter((line) => !isAutoGeneratedRemarkLine(line));

  return userLines.join("\n").trim();
}

/**
 * One auto line per key+number. Collapses "Based on PQ 123" + SAP
 * "Based On Purchase Quotations 123" so remarks do not show PQ twice.
 */
export const dedupeRemarkChainLines = (remarks: string): string => {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const line of splitRemarkLines(remarks)) {
    const parsed = parseAutoRemarkKeyAndNum(line);
    if (parsed) {
      const id = `${parsed.key}:${parsed.num}`;
      if (seen.has(id)) {
        continue;
      }
      seen.add(id);
    }
    out.push(line);
  }
  return out.join("\n");
};

/**
 * Copy-from remarks: keep user text + existing chain, add new source refs only
 * when that type is not already present (PQ inherited from IC, etc.).
 */
export const composeCopySourceRemarks = (sourceComments: string, newRefs: string[]): string => {
  const lines = splitRemarkLines(sourceComments);
  const autoLines = lines.filter((line) => isAutoGeneratedRemarkLine(line));
  const userLines = lines.filter((line) => !isAutoGeneratedRemarkLine(line));
  const seenKeys = new Set<string>();
  const seenIds = new Set<string>();
  const keptAuto: string[] = [];

  const remember = (line: string): boolean => {
    const parsed = parseAutoRemarkKeyAndNum(line);
    if (!parsed) {
      const fallback = line.toLowerCase();
      if (seenIds.has(fallback)) {
        return false;
      }
      seenIds.add(fallback);
      return true;
    }
    const id = `${parsed.key}:${parsed.num}`;
    if (seenKeys.has(parsed.key) || seenIds.has(id)) {
      return false;
    }
    seenKeys.add(parsed.key);
    seenIds.add(id);
    return true;
  };

  for (const line of autoLines) {
    if (remember(line)) {
      keptAuto.push(line);
    }
  }
  for (const ref of newRefs) {
    const trimmed = ref.trim();
    if (!trimmed) {
      continue;
    }
    if (remember(trimmed)) {
      keptAuto.push(trimmed);
    }
  }

  return dedupeRemarkChainLines([...keptAuto, ...userLines].join("\n"));
};
